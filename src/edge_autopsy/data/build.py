def build_french(raw_dir: Path, processed_dir: Path, files: Mapping[str, str]) -> dict[str, Path]:
    """Parse the three French zips; write ff49_vw_daily.parquet and ff_factors_daily.parquet."""
    raw = Path(raw_dir) / "french"
    processed_dir = Path(processed_dir)
    processed_dir.mkdir(parents=True, exist_ok=True)

    ind = clean_french_ind49(read_zip_text(raw / files["ind49_daily"]))
    ff3 = clean_french_ff3(read_zip_text(raw / files["ff3_daily"]))
    mom = clean_french_mom(read_zip_text(raw / files["mom_daily"]))

    if not ff3.index.equals(ind.index):
        raise DataError("49-industry and FF3 daily files have different trading-day calendars")
    extra = mom.index.difference(ff3.index)
    if len(extra):
        raise DataError(f"momentum file has {len(extra)} dates not in FF3, e.g. {extra[:3]}")
    factors = ff3.join(mom, how="left")  # mom starts 1926-11-03: earlier rows stay NaN

    out = {
        "ff49_vw_daily": processed_dir / "ff49_vw_daily.parquet",
        "ff_factors_daily": processed_dir / "ff_factors_daily.parquet",
    }
    ind.to_parquet(out["ff49_vw_daily"])
    factors.to_parquet(out["ff_factors_daily"])
    return out


def audit_french(
    processed_dir: Path,
    entry_days: int,
    min_assets: int,
    floor: pd.Timestamp | None,
    flag_abs: float = 0.5,
) -> dict:
    """D3: availability flags, sample start, extremes, |ret| flags and a markdown audit.

    Data-quality statistics only (counts, extremes). Nothing here measures predictability,
    so computing it over hold-out dates does not break the seal (CLAUDE.md rule 4).
    """
    processed_dir = Path(processed_dir)
    r = pd.read_parquet(processed_dir / "ff49_vw_daily.parquet")
    av = availability(r, entry_days)
    av.to_parquet(processed_dir / "ff49_available.parquet")
    start = first_sample_date(av, min_assets, floor=floor)

    by_year = r.notna().groupby(r.index.year).sum()
    by_year.index.name = "year"
    by_year.to_csv(processed_dir / "nonmissing_by_year.csv")

    flags = top_abs_returns(r, int(r.notna().sum().sum()))
    flags = flags[flags["ret"].abs() >= flag_abs]
    flags.to_csv(processed_dir / "flags.csv", index=False)

    rb = rebalance_dates(r.index)
    counts = av.loc[rb].sum(axis=1)
    in_sample = counts[start:]
    first_valid = pd.to_datetime(r.apply(lambda c: c.first_valid_index()))
    gaps = {c: int(r[c].loc[first_valid[c] :].isna().sum()) for c in r.columns}

    def md_table(df: pd.DataFrame) -> str:
        cols = list(df.columns)
        rows = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
        for _, row in df.iterrows():
            rows.append("| " + " | ".join(str(v) for v in row.to_numpy()) + " |")
        return "\n".join(rows)

    def fmt_top(df: pd.DataFrame) -> pd.DataFrame:
        out = df.copy()
        out["date"] = out["date"].dt.strftime("%Y-%m-%d")
        out["ret"] = out["ret"].map(lambda v: f"{v:+.4f}")
        return out

    late = first_valid[first_valid > r.index[0]].sort_values()
    lines = [
        "# Data audit: French 49 industries, VW daily (generated by `audit_french`)",
        "",
        f"- Dates: {r.index[0]:%Y-%m-%d} to {r.index[-1]:%Y-%m-%d}, {len(r):,} trading days",
        f"- Entry rule: available from the {entry_days}th non-missing day; NaN is never available",
        f"- Sample floor: {floor:%Y-%m-%d}" if floor is not None else "- Sample floor: none",
        f"- **Sample start: {start:%Y-%m-%d}** (first rebalance date >= floor with "
        f">= {min_assets} available); available that day: {int(counts[start])}",
        f"- Available industries on rebalance dates from sample start: min "
        f"{int(in_sample.min())}, max {int(in_sample.max())}; all 49 from "
        f"{counts[counts == r.shape[1]].index[0]:%Y-%m-%d}"
        if (counts == r.shape[1]).any()
        else "- Never all industries available",
        f"- Cells with |ret| >= {flag_abs}: {len(flags)} (see flags.csv; flagged, not dropped)",
        "",
        "## Industries starting after the first date",
        "",
        md_table(
            pd.DataFrame(
                {"asset": late.index, "first_valid": pd.to_datetime(late).dt.strftime("%Y-%m-%d")}
            )
        ),
        "",
        "## Missing days after an industry's first valid day",
        "",
        md_table(
            pd.DataFrame({"asset": list(gaps), "nan_days": list(gaps.values())}).query(
                "nan_days > 0"
            )
        ),
        "",
        "## 10 largest |daily return|, full history",
        "",
        md_table(fmt_top(top_abs_returns(r, 10))),
        "",
        f"## 10 largest |daily return| from sample start ({start:%Y-%m-%d})",
        "",
        md_table(fmt_top(top_abs_returns(r.loc[start:], 10))),
        "",
        "Per-industry, per-year non-missing counts: `nonmissing_by_year.csv`.",
        "",
    ]
    (processed_dir / "data_audit.md").write_text("\n".join(lines), encoding="utf-8")
    return {"sample_start": start, "n_flags": len(flags), "available_at_start": int(counts[start])}


def build_etf(raw_dir: Path, processed_dir: Path, tickers: list[str], benchmark: str) -> Path:
    """D5: total returns + dollar volume for the ETFs and the benchmark, long format."""
    processed_dir = Path(processed_dir)
    processed_dir.mkdir(parents=True, exist_ok=True)
    frames = []
    for t in [*tickers, benchmark]:
        bars = load_etf_raw(raw_dir, t)
        frames.append(
            pd.DataFrame(
                {
                    "date": bars.index,
                    "asset": t,
                    "ret": etf_total_returns(bars).to_numpy(),
                    "volume_usd": (bars["Close"] * bars["Volume"]).to_numpy(),
                }
            )
        )
    out = pd.concat(frames, ignore_index=True)
    path = processed_dir / "etf9_daily.parquet"
    out.to_parquet(path, index=False)
    return path


def build_panel(
    processed_dir: Path,
    etf_tickers: list[str],
    benchmark: str,
    entry_days: int,
    sample_end: pd.Timestamp,
) -> Path:
    """D6: merge ff49, etf9, RF and market into the long schema of PLAN §5.2."""
    processed_dir = Path(processed_dir)
    end = pd.Timestamp(sample_end)
    ind = pd.read_parquet(processed_dir / "ff49_vw_daily.parquet").loc[:end]
    fac = pd.read_parquet(processed_dir / "ff_factors_daily.parquet").loc[:end]
    etf = pd.read_parquet(processed_dir / "etf9_daily.parquet")
    etf = etf[etf["date"] <= end]

    # ff49: wide -> long, availability from the entry rule, FF RF and market
    av = availability(ind, entry_days)
    ff = (
        ind.rename_axis(index="date", columns="asset")
        .reset_index()
        .melt(id_vars="date", var_name="asset", value_name="ret")
    )
    ff["available"] = (
        av.rename_axis(index="date", columns="asset")
        .reset_index()
        .melt(id_vars="date", var_name="asset", value_name="a")["a"]
        .to_numpy()
    )
    ff["universe"] = "ff49"
    ff["volume_usd"] = float("nan")
    ff = ff.join(fac[["rf", "mkt"]], on="date")

    # etf9: tradables only; benchmark return becomes the `mkt` column
    wide = etf.pivot(index="date", columns="asset", values="ret")
    vol = etf.pivot(index="date", columns="asset", values="volume_usd")
    missing_rf = wide.index.difference(fac.index)
    if len(missing_rf):
        raise DataError(f"{len(missing_rf)} ETF dates have no FF rf, e.g. {list(missing_rf[:3])}")
    tr = wide[etf_tickers]
    eav = availability(tr, entry_days)
    parts = []
    for t in etf_tickers:
        parts.append(
            pd.DataFrame(
                {
                    "date": tr.index,
                    "asset": t,
                    "ret": tr[t].to_numpy(),
                    "available": eav[t].to_numpy(),
                    "universe": "etf9",
                    "volume_usd": vol[t].to_numpy(),
                    "rf": fac["rf"].reindex(tr.index).to_numpy(),
                    "mkt": wide[benchmark].to_numpy(),
                }
            )
        )
    panel = pd.concat([ff, *parts], ignore_index=True)
    panel["date"] = panel["date"].astype("datetime64[ns]")
    panel["asset"] = panel["asset"].astype("category")
    panel["universe"] = panel["universe"].astype("category")
    panel["available"] = panel["available"].astype(bool)
    panel = panel.sort_values(["universe", "asset", "date"], kind="stable").reset_index(drop=True)
    panel = panel[PANEL_COLUMNS]
    path = processed_dir / "panel.parquet"
    panel.to_parquet(path, index=False)
    return path


def french_revision_diff(old_zip: Path, new_zip: Path) -> dict:
    """Cell-level diff of two versions of the 49-industry VW daily file (PLAN §5.3 rule 8)."""
    old = clean_french_ind49(read_zip_text(old_zip))
    new = clean_french_ind49(read_zip_text(new_zip))
    common = old.index.intersection(new.index)
    a, b = old.loc[common], new.loc[common, old.columns]
    changed = ~((a == b) | (a.isna() & b.isna()))
    diff = (a - b).abs()
    return {
        "changed_cells": int(changed.to_numpy().sum()),
        "max_abs_change": float(np.nanmax(diff.to_numpy())) if changed.to_numpy().any() else 0.0,
        "new_dates": len(new.index.difference(old.index)),
        "dropped_dates": len(old.index.difference(new.index)),
        "first_changed_date": (
            f"{changed.any(axis=1).idxmax():%Y-%m-%d}" if changed.to_numpy().any() else None
        ),
    }


def check_sample_start(
    computed: pd.Timestamp, configured: pd.Timestamp | None, base_yaml: Path
) -> str:
    """Write sample_start the first time; afterwards refuse to let a data revision move it."""
    if configured is None:
        write_sample_start(base_yaml, computed)
        return "written"
    if pd.Timestamp(configured) != pd.Timestamp(computed):
        raise DataError(
            f"data now gives sample_start {computed:%Y-%m-%d} but base.yaml says "
            f"{pd.Timestamp(configured):%Y-%m-%d}. A data revision moved the sample: review "
            f"MANIFEST.json revisions and update base.yaml deliberately (DECISIONS log)."
        )
    return "ok"


def _report_french_revisions(raw_dir: Path, processed_dir: Path, files: Mapping[str, str]) -> list:
    """Diff report for every archived 49-industry revision (PLAN §5.3 rule 8, K9)."""
    m = load_manifest(raw_dir)
    out = []
    for rev in m["revisions"]:
        if rev["name"] != "ind49_daily" or not rev.get("archived_as"):
            continue
        d = french_revision_diff(
            Path(raw_dir) / rev["archived_as"], Path(raw_dir) / "french" / files["ind49_daily"]
        )
        out.append({**rev, **d})
    if out:
        lines = ["# French 49-industry revisions (old archived file vs current)", ""]
        lines += [f"- {r['detected_at']}: {r}" for r in out]
        (Path(processed_dir) / "revision_report.md").write_text("\n".join(lines), encoding="utf-8")
        for r in out:
            print(
                f"REVISION ind49_daily: {r['changed_cells']} cells changed, "
                f"max |change| {r['max_abs_change']:.6f}, new dates {r['new_dates']}"
            )
    return out


def build_all(root: Path, offline: bool = False, refresh: bool = False) -> dict:
    """`tasks.py data`: download (unless offline) -> clean -> audit -> ETF -> panel -> validate."""
    root = Path(root)
    base_yaml = root / "configs" / "base.yaml"
    cfg = load_config(base_yaml)
    d = cfg.data
    raw, proc = root / "data" / "raw", root / "data" / "processed"
    end = pd.Timestamp(d.sample_end)

    print("[1/7] French downloads", "(offline)" if offline else "")
    download_french_all(d.french_files, d.french_base_url, raw, offline=offline, refresh=refresh)
    revisions = _report_french_revisions(raw, proc, d.french_files)
    print("[2/7] Parse French files")
    build_french(raw, proc, d.french_files)
    print("[3/7] Audit + sample start")
    audit = audit_french(
        proc, d.entry_days, d.min_industries, pd.Timestamp(d.sample_floor), d.max_abs_ret_flag
    )
    status = check_sample_start(audit["sample_start"], d.sample_start, base_yaml)
    print(f"      sample_start {audit['sample_start']:%Y-%m-%d} ({status})")
    print("[4/7] ETF downloads", "(offline)" if offline else "")
    tickers = [*d.etf_tickers, d.etf_benchmark]
    etf_end = f"{end + pd.Timedelta(days=1):%Y-%m-%d}"  # yfinance `end` is exclusive
    download_etfs(tickers, str(d.etf_start), etf_end, raw, offline=offline, refresh=refresh)
    check_etf_first_dates(raw, tickers, pd.Timestamp(d.etf_first_date_max))
    print("[5/7] ETF total returns")
    build_etf(raw, proc, d.etf_tickers, d.etf_benchmark)
    print("[6/7] Build panel")
    path = build_panel(proc, d.etf_tickers, d.etf_benchmark, d.entry_days, end)
    print("[7/7] Validate panel")
    panel = pd.read_parquet(path)
    ind_names = pd.read_parquet(proc / "ff49_vw_daily.parquet").columns
    rep = validate_panel(
        panel,
        expected_assets={"ff49": set(ind_names), "etf9": set(d.etf_tickers)},
        entry_days=d.entry_days,
        sample_end=end,
        flag_abs=d.max_abs_ret_flag,
    )
    version = manifest_hash(raw)
    print(
        f"OK panel.parquet: {rep['n_rows']:,} rows, {rep['n_available']:,} available, "
        f"{rep['n_flags']} flagged |ret|>={d.max_abs_ret_flag}, ranges {rep['date_range']}, "
        f"data version {version[:12]}"
    )
    return {
        "panel": str(path),
        "sample_start": f"{audit['sample_start']:%Y-%m-%d}",
        "validation": {k: v for k, v in rep.items() if k != "flags"},
        "data_version": version,
        "revisions": revisions,
    }
